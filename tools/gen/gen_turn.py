def gen_plate(seeds, steps=25, prompt=None, negative=None, prefix="plate_s"):
    made = []
    for seed in seeds:
        tag = f"{prefix}{seed}"
        spec = {"tag": tag, "width": 864, "height": 1536, "seed": seed,
                "steps": steps, "prompt": prompt or PLATE_PROMPT,
                "negative": negative or PLATE_NEG}
        made.append(qw.t2i(spec))
    return made


def gen_anchor(steps=25, seed=1):
    return qw.edit(OLD / "char_ref.png", ANCHOR_INSTR, "char_anchor", seed=seed, steps=steps)


def gen_hero(plate, anchor, seed=771, steps=25, close=False):
    if close:
        return qw._edit_wf([plate, anchor], COMPOSE_CLOSE_INSTR, "hero_close", seed=seed,
                           steps=steps, negative=COMPOSE_CLOSE_NEG)
    return qw._edit_wf([plate, anchor], COMPOSE_INSTR, "hero", seed=seed, steps=steps,
                       negative=COMPOSE_NEG)


def gen_clean(hero, steps=25, seed=1, close=False):
    instr = REMOVE_CLOSE_INSTR if close else REMOVE_INSTR
    tag = "plate_clean" if close else "plate_clean_wide"
    return qw.edit(hero, instr, tag, seed=seed, steps=steps)


def gen_states(hero, only=None, steps=25, seed=1):
    made = []
    for name, instr in STATES.items():
        if only and name not in only:
            continue
        made.append(qw.edit(hero, CONST + instr + ". Keep the background, the crop and the props "
                            "unchanged. Do not add or remove any object. Do not change the hair "
                            "or the coat.", f"state_{name}", seed=seed, steps=steps))
    return made


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["plate", "plate_close", "anchor_cam", "hero", "clean", "states"])
    ap.add_argument("--seeds", default="771,2024")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--steps", type=int, default=25)
    ap.add_argument("--close", action="store_true")
    ap.add_argument("--plate", default=str(RAW / "plate_s771.png"))
    ap.add_argument("--anchor", default=str(RAW / "char_anchor.png"))
    ap.add_argument("--hero", default=str(RAW / "hero.png"))
    ap.add_argument("--only", default="")
    a = ap.parse_args()
    if a.cmd == "plate":
        print(gen_plate([int(s) for s in a.seeds.split(",") if s], a.steps))
    elif a.cmd == "plate_close":
        print(gen_plate([int(s) for s in a.seeds.split(",") if s], a.steps,
                        prompt=CLOSE_PROMPT, negative=CLOSE_NEG, prefix="plate_close_s"))
    elif a.cmd == "anchor_cam":
        print(gen_anchor(a.steps, a.seed))
    elif a.cmd == "hero":
        print(gen_hero(Path(a.plate), Path(a.anchor), a.seed, a.steps, close=a.close))
    elif a.cmd == "clean":
        print(gen_clean(Path(a.hero), a.steps, a.seed, close=a.close))
    else:
        only = [s for s in a.only.split(",") if s] or None
        print(gen_states(Path(a.hero), only, a.steps, a.seed))
    return 0


if __name__ == "__main__":
    sys.exit(main())
